"""Rebuild selected cards from the declared research-input pack, without page transactions."""
import argparse
import hashlib
import json
import sys
from pathlib import Path


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--input-root', type=Path, required=True)
    ap.add_argument('--output', type=Path, required=True)
    ap.add_argument('--cids', type=int, nargs='+', required=True)
    args = ap.parse_args()
    root = args.input_root.resolve()
    dest = args.output.resolve()
    dest.mkdir(parents=True, exist_ok=False)
    sys.path.insert(0, str(root / 'scripts/character_skills'))
    from card_page_data import Inputs, build_card
    from card_page_render_v2 import page
    from card_page import validate
    inputs = Inputs(root, args.cids)
    result = []
    for cid in args.cids:
        card = build_card(inputs, cid)
        html = page(card)
        validate(card, html)
        target = dest / str(cid)
        target.mkdir()
        raw = json.dumps(card, ensure_ascii=False, indent=2, allow_nan=False) + '\n'
        (target / 'card.json').write_text(raw, encoding='utf-8')
        (target / 'index.html').write_text(html, encoding='utf-8')
        expected = root / 'output/character_skills/pages' / str(cid)
        old = json.loads((expected / 'card.json').read_text(encoding='utf-8'))
        # Transaction provenance is generated by the full page runner, not build_card.
        old.pop('input_snapshot', None)
        rebuilt = dict(card)
        rebuilt.pop('input_snapshot', None)
        same = rebuilt == old
        written_html = (target / 'index.html').read_bytes()
        same_html = (expected / 'index.html').read_bytes() == written_html
        result.append(dict(cid=cid, card_equal_except_transaction_snapshot=same,
                           html_exact=same_html, html_sha256=hashlib.sha256(written_html).hexdigest()))
    report = dict(status='PASS' if all(x['card_equal_except_transaction_snapshot'] and x['html_exact'] for x in result) else 'FAIL',
                  cards=result, scope='Representative generation only; no full campaign, ledger or reservation writes.')
    (dest / 'report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report, ensure_ascii=False))
    if report['status'] != 'PASS':
        raise SystemExit(1)


if __name__ == '__main__':
    main()
