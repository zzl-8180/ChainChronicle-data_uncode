def _boss_extra_rules() -> list[dict]:
    """Rules confirmed by the boss heal/chain line but absent from the 77-rule merge.

    ``output/boss_heal/field_dictionary.json`` carries rules the 77-rule merge lacks
    (game-second units, the type27 super-limit flag table). The merge in
    :func:`rules` keeps ``card_comparison_cid30236/field_dictionary.json`` first and
    only fills *missing* keys from here, so on the single overlapping key
    (``bossskill|13|/skillparam2``) the card_comparison wording wins; the boss_heal
    variant states the same rule differently (both give
    ``_normalAtk x guardRate`` with the same nominal-ATK conversion). Entries lacking
    ``table`` are mapped to the ``bossskill`` namespace they were derived from
    (``file_table`` says ``bossinfo.data5 / bossinfo.bossskill``).
    """
    src = Path("output") / "boss_heal" / "field_dictionary.json"
    out = []
    for r in load_json(src):
        ft = r.get("file_table") or ""
        if "bossskill" not in ft:
            continue
        fp = r.get("field_path") or ""
        if not fp.startswith("/"):
            fp = "/" + fp
        out.append({
            "source": "CACHE",
            "table": "bossskill",
            "record_type": f"skillid0={r.get('effect_type')}",
            "effect_type": r.get("effect_type"),
            "field_path": fp,
            "meaning_zh": r.get("meaning_zh"),
            "unit": r.get("unit"),
            "conversion": r.get("rule"),
            "base_definition": None,
            "status": r.get("status"),
            "applicability": r.get("condition"),
            "evidence": [("output/boss_heal/field_dictionary.json", "output/boss_heal/README.md")],
            "limits": ("以 Boss skill 经 initialize_ExAttack 进入对应 type 处理器为前提；"
                       "当前装载与实机最终数值另论"),
            "target": None,
            "occurrences": None,
            "origin": "output/boss_heal/field_dictionary.json",
        })
    return out


