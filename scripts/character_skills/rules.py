_NEUTRAL = "本项中性（原值 1）"


def _pct(x: float) -> str:
    return f"{x * 100:+.4g}".rstrip("0").rstrip(".") if abs(x * 100 - round(x * 100)) > 1e-9 else f"{x * 100:+.0f}"


def _num(x) -> str:
    if isinstance(x, float):
        s = f"{x:.6g}"
        return s
    return str(x)


def _mult_kind(value, *, label: str, up_word: str, down_word: str, kind: str, unit: str):
    if value == 1:
        text = f"{label}×1 → {_NEUTRAL}"
    else:
        delta = (value - 1) * 100
        word = up_word if delta > 0 else down_word
        text = f"{label}×{_num(value)}（本项{word} {abs(delta):.6g}%）"
    return {"quantity_kind": kind, "value_text": text, "unit": unit}


def _take_kind(value, *, unit="无量纲倍率"):
    if value == 1:
        return {"quantity_kind": "受伤量倍率", "value_text": f"受伤量×1 → {_NEUTRAL}", "unit": unit}
    if value < 1:
        return {"quantity_kind": "受伤量倍率", "value_text": f"受伤量×{_num(value)}（本项减伤 {(1 - value) * 100:.6g}%；不是固定防御量）", "unit": unit}
    return {"quantity_kind": "受伤量倍率", "value_text": f"受伤量×{_num(value)}（本项增伤 {(value - 1) * 100:.6g}%）", "unit": unit}


