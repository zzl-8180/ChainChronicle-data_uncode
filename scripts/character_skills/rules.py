def rules() -> list[dict]:
    global _RULES
    if _RULES is None:
        merged = list(load_json(CARD_COMPARISON / "field_dictionary.json"))
        have = {(r.get("table"), _rule_effect_type(r), r.get("field_path")) for r in merged}
        for r in (_boss_extra_rules() + _skilllist_type_rules() + _boss_attack_type_rules()
                  + _boss_heal_type_rules()
                  + (load_json(Path('output/character_skills/remaining_five/field_dictionary.json'))
                     if Path('output/character_skills/remaining_five/field_dictionary.json').exists() else [])):
            key = (r["table"], r["effect_type"], r["field_path"])
            if key not in have:
                merged.append(r)
                have.add(key)
        _RULES = merged
    return _RULES


def rule_index() -> dict:
    """(table, effect_type, field_path) -> rule record.

    ``charainfo`` is an *alias* table: the character record's own special-move
    parameters (``skillparam0..9``) share both the value domain
    (``charainfo.skillid[0]`` == ``bossskill.skillid0``) and the slot layout of the
    boss records -- proven by ``BtlCharaUtil.CharaParamToBossSkill``, which copies
    ``skillparamN -> skillparamN`` index aligned into a ``BattleBossSkill``. The
    alias is therefore registered here, but it is only *sound for a given record*
    when the record-level equivalence in ``equivalence.py`` holds (the confirmable
    caller is ``profiles.collect_answers``, which refuses the transfer otherwise).
    Without that gate the alias must not be used.
    """
    global _RULE_INDEX
    if _RULE_INDEX is None:
        idx = {}
        for r in rules():
            key = (r.get("table"), _rule_effect_type(r), r.get("field_path"))
            idx[key] = r
            if r.get("table") == "bossskill":
                idx.setdefault(("charainfo", _rule_effect_type(r), r.get("field_path")), r)
        _RULE_INDEX = idx
    return _RULE_INDEX


def views_index() -> dict:
    """(table, record_id, field_path) -> review row from the generated views."""
    global _VIEWS
    if _VIEWS is None:
        rows = load_json(CARD_COMPARISON / "verified_parameter_views.json")
        idx = {}
        for r in rows:
            idx.setdefault((r.get("table"), r.get("record_id"), r.get("field_path")), r)
        _VIEWS = idx
    return _VIEWS


def view_for(table: str, record_id, field_path: str):
    return views_index().get((table, record_id, field_path))


def rule_for(table: str, effect_type, field_path: str):
    return rule_index().get((table, effect_type, field_path))


