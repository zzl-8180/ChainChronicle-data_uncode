# --- P2 batch 6: filter dictionaries (job / weapon / home) --------------------
# The three filters the count conditions use. The names come from the recovered
# metadata enums and from the game's own master table ``homelist``; the *bit shapes*
# are read out of the native code (see skilllist_types.filter_dictionary).
JOB_TYPE_NAMES = {0: "戦士(WARRIOR)", 1: "弓使い(ARCHERY)", 2: "魔法使い(WIZARD)",
                  3: "僧侶(HEALER)", 4: "騎士(SHIELD)", 5: "ALMIGHTY"}
WEAPON_FLAG_BITS = {22: "斬(SWORD)", 23: "打(AXE)", 24: "突(MACE)", 25: "弓(BOW)",
                    26: "魔(EVIL)", 27: "聖(HOLY)", 28: "拳(FIST)", 29: "銃(GUN)",
                    30: "狙(RIFLE)"}
WEAPON_FLAG_MASK = 0x7FC00000
# the record fields that carry the two 64-bit filter words (low half only; the weapon
# bits 22..30 all live below bit 32, so the low word is sufficient)
WEAPON_LOW_FIELDS = ("flag0_0", "flag1_0")
_HOMELIST: dict | None = None


def homelist() -> dict:
    """``homelist.home_id`` -> name, the game's own master table for 出身."""
    global _HOMELIST
    if _HOMELIST is None:
        doc = load_json(DECODED / "homelist.data5.json.raw")
        _HOMELIST = {int(r["home_id"]): r["name"] for r in doc["homelist"]}
    return _HOMELIST


def decode_job_bits(mask) -> list[str]:
    try:
        m = int(mask)
    except (TypeError, ValueError):
        return []
    return [JOB_TYPE_NAMES[i] for i in range(6) if m & (1 << i)]


def decode_weapon_bits(mask) -> list[str]:
    try:
        m = int(mask) & WEAPON_FLAG_MASK
    except (TypeError, ValueError):
        return []
    return [WEAPON_FLAG_BITS[i] for i in range(22, 31) if m & (1 << i)]


def decode_home_codes(value) -> dict:
    """出身筛选值: up to three two-digit groups compared against the chara's home.

    Same shape as the terrain code: the value's 1/100/10000 positions each hold a
    2-digit home id. 0 means "no home filter".
    """
    try:
        n = int(value)
    except (TypeError, ValueError):
        return {"raw": value, "groups": [], "names": []}
    if n == 0:
        return {"raw": 0, "groups": [], "names": [],
                "note": "0＝不按出身筛选（IsTargetHome 在 targetHome==0 时直接为真）"}
    groups = [n % 100, (n // 100) % 100, (n // 10000) % 100]
    groups = [g for g in groups if g]
    names = [homelist().get(g, f"未在 homelist 的取值 {g}") for g in groups]
    return {"raw": n, "groups": groups, "names": names}


def _filter_values(record: dict) -> dict:
    r = record or {}
    return {
        "iParam0": r.get("iParam0"),
        "iParam1": r.get("iParam1"),
        "param8": r.get("param8"),
        "param9": r.get("param9"),
        "flag0_0": r.get("flag0_0"),
        "flag1_0": r.get("flag1_0"),
    }


def _job_phrase(v, *, missing="（记录无 iParam0 → 位图 0，不按职业筛选）"):
    if v in (None, 0, 0.0):
        return missing
    names = decode_job_bits(v)
    return "、".join(names) if names else f"未知置位（原值 {v}）"


def _weapon_phrase(v, *, field="flag0_0"):
    if v in (None, 0, 0.0):
        return f"（{field}=0 → 不按武器筛选）"
    names = decode_weapon_bits(v)
    return "、".join(names) if names else f"未知置位（原值 {v}）"


def _home_phrase(v, *, label="param8"):
    d = decode_home_codes(v if v is not None else 0)
    if not d["groups"]:
        return f"（{label}=0 → 不按出身筛选）"
    return "、".join(d["names"])


