SCRAP_MANA_NOTE = ("斯库拉普玛那（scrap，PanelManaGage.GetCurrentScrapManaNum，标志 0x20）")
MANA_OBJECT_FALLBACK = "玛那计数（对象由 int(param0) 选择：0 为斯库拉普玛那，否则为 iParam0 选取的当前玛那）"


def _mana_object(record):
    """The counting object of a type-96 record, from its own param0.

    The branch does ``fcmp(+inf)`` / ``fcvtzs`` / ``cbnz`` on ``param0``: a zero
    (truncated) value takes the scrap-mana path, everything else the job-flag path.
    """
    p0 = (record or {}).get("param0")
    if not isinstance(p0, (int, float)) or isinstance(p0, bool):
        return MANA_OBJECT_FALLBACK, None
    if int(p0) == 0:
        return SCRAP_MANA_NOTE, int(p0)
    return "当前玛那数（按 iParam0 经 ConvJobFlagToElementFlag 选取）", int(p0)


def _mana_coeff(value, kind, record=None):
    label, qk, unit, mode = MANA_COEFF[kind]
    noun, p0 = _mana_object(record)
    term = f"{_num(value)} × min({noun}, param1)"
    tail = "（玛那计数与本记录 param1 上限均为运行时值）"
    if mode == "乘":
        text = f"{label} ×(1 + {term})" + tail
        if kind == "mana_coeff_take":
            text += "；不是固定防御量"
    else:
        text = f"{label} += {term}" + (" ×100 个百分点" if kind.endswith("rate") else "")
        text += tail
    out = {"quantity_kind": qk, "value_text": text, "unit": unit,
           "answer_status": "CONFIRMED_FORMULA_ONLY"}
    if p0 is None:
        out["note"] = ("本记录未见 param0，无法判定计数对象；按分支语义列出两种可能，"
                       "未经确认时不选定其中之一")
    return out


def _hyper(value, kind):
    label, qk, unit, mode = HYPER[kind]
    term = f"{_num(value)} × hyperGauge ÷ 1000"
    if mode in ("attack", "move", "take"):
        text = (f"{label} = 1 + {term}（hyperGauge＝BattleParam.get_hyperGauge()，运行时值；"
                "未装载时为 0 → 本项中性）")
    else:
        text = (f"{label} += {term}" + (" ×100 个百分点" if mode == "crit_rate" else "")
                + "（hyperGauge 为运行时值，未装载时为 0）")
    return {"quantity_kind": qk, "value_text": text, "unit": unit,
            "answer_status": "CONFIRMED_FORMULA_ONLY"}


