def answer_for(table: str, effect_type, field_path: str, value, record: dict) -> dict | None:
    """Full answer row for one field of one record, or None when no rule exists."""
    rule = rule_for(table, effect_type, field_path)
    if rule is None:
        return None
    derived = convert(table, effect_type, field_path, value, record, rule)
    out = {
        "field_path": field_path,
        "effect_type": effect_type,
        "raw_value": value,
        "meaning_zh": rule.get("meaning_zh"),
        "unit": (derived or {}).get("unit") or rule.get("unit"),
        "conversion": rule.get("conversion"),
        "base_definition": rule.get("base_definition"),
        "target": rule.get("target"),
        "conditions": rule.get("applicability"),
        "evidence": rule.get("evidence"),
        "rule_status": rule.get("status"),
        "rule_limits": rule.get("limits"),
        "occurrences": rule.get("occurrences"),
    }
    if derived:
        out.update({
            "quantity_kind": derived.get("quantity_kind"),
            "value_text": derived.get("value_text"),
            # a converter may declare a weaker status when its answer still carries a
            # runtime factor (the mana count / hyper gauge terms); default stays numeric
            "answer_status": derived.get("answer_status") or "CONFIRMED_NUMERIC",
        })
        for extra in ("base", "note"):
            if derived.get(extra):
                out[extra] = derived[extra]
    else:
        out.update({
            "quantity_kind": None,
            "value_text": f"公式：{rule.get('conversion')}（本类型未写数值换算器，公式本身即答案）",
            "answer_status": "CONFIRMED_FORMULA_ONLY",
        })
    return out


