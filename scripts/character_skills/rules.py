EXTRA_NUMERIC_KEYS = {
    "time", "used_skilltime", "appear_flag", "appear_flag_num",
    "hpend", "scost", "pose", "priority", "limit",
}


def is_param_like(key: str) -> bool:
    """Numeric parameter slots.

    ``str*`` fields are resource/effect name strings, not numeric parameters;
    they stay in the raw record but are not counted as "unexplained numbers".
    """
    return (key.startswith(("param", "iParam", "iparam", "skillparam", "flag", "skillflag"))
            or key in EXTRA_NUMERIC_KEYS)


def unexplainable_notes(table: str, effect_type, key: str) -> str:
    if not is_param_like(key):
        return "非参数类字段，不在本层规则范围"
    rule = rule_for(table, effect_type, "/" + key)
    if rule is None:
        return f"当前 {table} 类型 {effect_type} 的 /{key} 没有已确认规则"
    return "有规则但原值不是有限数值"


