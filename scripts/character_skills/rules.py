def _union_mult(value, kind, record=None):
    label, qk, unit, mode = UNION_MULT[kind]
    vals = _filter_values(record)
    target = (f"对象＝通过筛选的成员（职业位图 iParam1={_job_phrase(vals['iParam1'], missing='0 → 不按职业限定')}；"
              f"武器位图 {_weapon_phrase(vals['flag1_0'], field='flag1_0')}；"
              f"出身 param9={_home_phrase(vals['param9'], label='param9')}），"
              "为队伍范围（玩家侧）施加，不是只作用于自身")
