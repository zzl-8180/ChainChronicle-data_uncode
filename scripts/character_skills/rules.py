def laser_config(field_path, value):
    """Normal finite positive Boss55 configuration; None does not mean zero."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    try:
        f32 = struct.unpack('<f', struct.pack('<f', value))[0]
    except (OverflowError, struct.error):
        return None
    if not math.isfinite(f32) or f32 <= 0:
        return None
    if field_path == '/skillparam6':
        return dict(quantity_kind='激光段生成调度阈值', unit='游戏秒',
            value_text=f'原值{value!r}；float32调度阈值{f32:.9g} 游戏秒（固定更新每步至多启用一段）',
            note='调度阈值不是严格受伤间隔；首段启用不代表即时命中。')
    if field_path == '/skillparam0' and 1 <= f32 < 2147483648:
        return dict(quantity_kind='激光段启用上限（含首段）', unit='段',
            value_text=f'{int(f32)} 段（float32后向零截断，含首段；非保证命中次数）')
    return None


def convert(table: str, effect_type, field_path: str, value, record: dict,
            rule: dict | None = None) -> dict | None:
    """Return a derived answer for one (table, effect_type, field_path, value).

    ``charainfo`` delegates to the ``bossskill`` converters: the alias is
    registered in :func:`rule_index` and is only valid under the record-level
    equivalence premise documented there.
    """
    if table == "charainfo":
        return convert("bossskill", effect_type, field_path, value, record, rule)
    if table == 'bossskill' and effect_type == 55 and field_path in ('/skillparam0', '/skillparam6'):
        return laser_config(field_path, value) or dict(quantity_kind='激光配置未解释',
            value_text=f'原值{value!r}不在本轮已确认的正常正值配置域，保留原值；不补零。',
            answer_status='UNRESOLVED', unit=None)
    if not isinstance(value, (int, float)) or isinstance(value, bool):
        return {"quantity_kind": "非数值原值", "value_text": repr(value), "unit": None}
    # generated rules may declare their own answer kind: the critical accumulators put
    # *different slots* on the rate/damage paths (param4/param5/param6/param7 depending on
    # the type), so the dispatch has to come from the rule row, not from the field name
    kind = (rule or {}).get("answer_kind")
    if kind == "crit_rate":
        return _pp(value, kind="暴击概率加算贡献", label="暴击率")
    if kind == "crit_dmg":
        return _crit_dmg(value, base_note=("本路径以 fadd 加算进暴伤系数，不减 1.5 基准；"
                                           "本路径汇总后夹在 [-1, 2]"))
    if kind == "attack_mult":
        return _mult_kind(value, label="自身攻击", up_word="提高", down_word="降低",
                          kind="攻击倍率", unit="无量纲倍率")
    if kind == "move_mult":
        return _move(value)
    if kind == "take_mult":
        return _take_kind(value)
    if kind in MANA_COEFF:
        return _mana_coeff(value, kind, record)
    if kind in HYPER:
        return _hyper(value, kind)
    if kind in ("chara_count_threshold", "mana_count_threshold", "mana_count_cap"):
        return _threshold_count(value, kind, record)
    if kind == "mana_selector":
        return _mana_selector(value)
    # --- P2 batch 6 ---
    if kind in MANA_COEFF_ATTACK:
        return _mana_coeff_attack(value, kind, record)
    if kind == "job_bitmap":
        return _job_bitmap(value, record)
    if kind == "weapon_bitmap":
        return _weapon_bitmap(value, record)
    if kind == "home_filter":
        return _home_filter(value, record)
    if kind in UNION_MULT:
        return _union_mult(value, kind, record)
    if kind == "union_count_threshold":
        return _union_count_threshold(value, record)
    if kind == "union_heal_coeff":
        return _union_heal_coeff(value, record)
    if kind == "union_heal_interval":
        return _union_heal_interval(value, record)
    if kind in BOSS_ATTACK_KINDS:
        return _boss_attack(value, kind, record, rule, effect_type)
    if kind in BOSS_HEAL_KINDS:
        return _boss_heal_type(value, kind, record, rule, effect_type)
    if kind == 'remaining_five' and table in ('bossskill', 'charainfo'):
        from remaining_five import convert as remaining_five_convert
        return remaining_five_convert(effect_type, field_path, value, record)

    if table == "skilllist":
        a = effect_type
        if a == 9 and field_path == "/param0":
            from type9_bullet import convert as bullet_retention_convert
            return bullet_retention_convert(value, record)
        # type 8 (Always) and the four types sharing its branch use the generic
        # answer_kind dispatch above ("attack_mult" / "move_mult" / "take_mult"), so the
        # conversion has exactly one implementation and the rule row is its source.
        if a == 26:
            if field_path == "/param0":
                from type26_mana import convert as mana_base_convert
                return mana_base_convert(value, record)
            # ManaGet: the mana produced at battle start (PlayerManager.PartyAbilityInit
            # -> subPartyAbilityInit_ManaGet). This batch traced the iParam1/param4 line
            # and the param7 line; the same function also has param0/param1/param2/param3
            # lines that are *not* interpreted here, so a "produces nothing" answer has
            # to stay scoped to its own line (review p2b2 problem 2).
            mana_scope = ("本句只就本字段这条产线成立；本类型另有 param0／param1／param2／param3 "
                          "四条产线（0x158cb8c／0x158cbf8／0x158ccb4／0x158cddc），本批未解释，"
                          "不能据此断言该能力整体不产玛那")
            if field_path == "/param4":
                n = int(value)
                return {"quantity_kind": "开局追加玛那数量",
                        "value_text": (f"战斗开始时追加 {n} 个玛那（可用职业受 iParam1 位图限定）")
                                      if n >= 1
                                      else f"原值 {value} → 取整 {n} < 1：param4 这条产线不产出追加玛那",
                        "unit": "个（int 向零截断）", "note": mana_scope}
            if field_path == "/param7":
                n = int(value)
                return {"quantity_kind": "开局追加玛那数量（不限职业）",
                        "value_text": (f"战斗开始时另行追加 {n} 个不限职业的玛那") if n >= 1
                                      else f"原值 {value} → 取整 {n} < 1：param7 这条产线不另行追加",
                        "unit": "个（int 向零截断）", "note": mana_scope}
            if field_path == "/iParam1":
                d = decode_job_mask(value)
                return {"quantity_kind": "可用职业位图",
                        "value_text": ("该追加玛那可被这些职业使用："
                                       + ("、".join(d["jobs"]) if d["jobs"]
                                          else "（无置位 → 这条产线不产出受职业限定的玛那）")),
                        "unit": "位图 1<<JobType", "base": f"mask={d['raw']} bits={d['bits']}",
                        "note": mana_scope}
            if field_path == "/param6":
                try:
                    m = int(value)
                except (TypeError, ValueError):
                    return None
                scope = {0: "仅当角色对象的范围标志非 0 时生效",
                         1: "无条件生效",
                         2: "仅当角色对象的范围标志为 0 时生效"}.get(m)
                return {"quantity_kind": "生效范围选择码",
                        "value_text": (f"选择码 {m} → {scope}" if scope
                                       else f"选择码 {m} 不在已确认的 0/1/2 分支内，不生效"),
                        "unit": "选择码（整数化）",
                        "note": "该范围标志字段的业务名未确认；0/1/2 以外的值三路都不命中"}
        # P2 batch 3: the two *additive* critical accumulators
        # (GetAbilityCritical / GetAbilityCriticalDmgRate). Critical rate is added in
        # percentage points and critical damage as a coefficient increment -- the two
        # are never each other's unit, and neither is a relative multiplier.
