def decode_terrain(param0) -> dict:
    """Two-digit decimal grouping (max three groups) -> bit mask, never a percentage."""
    try:
        n = int(param0)
    except (TypeError, ValueError):
        return {"error": "非整数原值，未按地形解码", "raw": param0}
    if n == 0:
        return {"code": 0, "groups": [], "bits": [], "note": "0 在函数入口直接通过（源 64 条中未出现）"}
    groups = [n % 100, (n // 100) % 100, (n // 10000) % 100]
    groups = [g for g in groups if g != 0]
    tb = terrain_bits()
    bits = []
    names = []
    unknown = []
    for g in groups:
        info = tb.get(str(g))
        if info:
            bits.append(info["bit"])
            for nm in info.get("background_names_ja", []):
                if nm not in names:
                    names.append(nm)
        else:
            unknown.append(g)
    return {
        "code": n,
        "groups": groups,
        "bits": bits,
        "terrain_names_ja": names,
        "unknown_group_indices": unknown,
    }


_JOB_NAMES = {0: "戦士(战士)", 1: "弓使い(弓手)", 2: "魔法使い(法师)", 3: "僧侶(僧侣)", 4: "騎士(骑士)", 5: "ALMIGHTY"}


def decode_job_mask(mask) -> dict:
    try:
        m = int(mask)
    except (TypeError, ValueError):
        return {"raw": mask, "jobs": []}
    jobs = [_JOB_NAMES[i] for i in range(6) if m & (1 << i)]
    high = m >> 6
    return {"raw": m, "bits": [i for i in range(6) if m & (1 << i)], "jobs": jobs,
            "unexplained_high_bits": high if high else 0}


def decode_trap_bitmap(code) -> dict:
    """type112 param8: 6x3 bitmap, bit i -> column i%6, row i//6."""
    try:
        c = int(code)
    except (TypeError, ValueError):
        return {"raw": code, "cells": []}
    cells = [[i % 6, i // 6] for i in range(18) if c & (1 << i)]
    return {"raw": c, "cells": cells, "count": len(cells)}


_SUPER_LIMIT_BITS = [40, 35, 41, 42, 43, 44]
_SUPER_LIMIT_VALUES = [1.2000000476837158, 1.2999999523162842, 1.399999976158142,
                       1.600000023841858, 1.7999999523162842, 2.0]


def decode_super_limit(flag0_1, shift: int = 32) -> dict | None:
    """Over-limit HP ratio from the flag table.

    The stored field holds the *low* 32 bits; the rule text is explicit that the
    value is shifted 32 bits first (``flag0_1左移32位；512→bit41`` for ability21 and
    ``高32位移位后…`` for type27). Selection then walks ``Constants.s_flagList`` in
    **reverse** order and takes the first set bit, so a value with several bits set
    yields the highest-priority one (native check: 2^42+2^43 → 1.8, not 1.6).
    With no bit set the ratio is 1.0 (native check: flag 0 → 1.0).
    """
    try:
        raw = int(flag0_1)
    except (TypeError, ValueError):
        return None
    v = raw << shift
    for i in range(len(_SUPER_LIMIT_BITS) - 1, -1, -1):
        bit = _SUPER_LIMIT_BITS[i]
        if v >> bit & 1:
            return {"raw": raw, "shifted": v, "selected_bit": bit,
                    "cap_ratio": _SUPER_LIMIT_VALUES[i],
                    "selection": "s_flagList 反序取首个已设置位"}
    return {"raw": raw, "shifted": v, "selected_bit": None, "cap_ratio": 1.0,
            "selection": "无超上限位置位 → 比率 1.0（不超上限）"}


