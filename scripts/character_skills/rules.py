"""Confirmed-rule layer for character skill answers.

Everything here is *reused* from already generated evidence. No new semantics is
invented: the rule set is the 77-entry ``field_dictionary.json`` and the 6613
per-field ``verified_parameter_views.json`` produced by the earlier ordinary /
boss lines. This module only turns those rules into per-record answers.

Two hard constraints are enforced by construction:

* ``type99`` ``param9`` is the *damage-taken* increment and ``param8`` is the
  single-sample move-speed increment. They are never swapped.
* Attack multiplier, damage-taken multiplier, flat guard and percentage points
  stay separate quantity kinds; missing / null / zero are never substituted.

The ``charainfo`` table is served as an *alias* of ``bossskill`` (same type domain,
same slot layout, proven by ``BtlCharaUtil.CharaParamToBossSkill``). The alias is
only sound where the record-level equivalence in ``equivalence.py`` holds; callers
must consult that gate before using a ``charainfo`` rule.

Rule sources, in merge order (a later source only fills keys the earlier ones lack):

1. ``card_comparison_cid30236/field_dictionary.json`` (the 77-entry dictionary)
2. ``boss_heal/field_dictionary.json`` (boss-side additions)
3. ``output/character_skills/skilllist_types/field_dictionary.json`` (P2 batch 2:
   ordinary ability types 8 = Always and 26 = ManaGet, each with the native dispatch
   index in the same directory)
"""
