"""Merge full-unpack shard results into the input ledger, coverage stats and manifest.

Run after full_unpack_run.py (also runnable mid-run for a partial view):
    .venv\\Scripts\\python.exe -B scripts/full_unpack_merge.py

Writes output/full_unpack/ledger.jsonl, coverage.json, manifest.json.
"""
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

INVENTORY = Path('output/cache_refresh_20261015/composite_inventory.jsonl')
OUTPUT = Path('output/full_unpack')
SHARDS = Path('work/full_unpack/shards')
V3_DECODED = Path('output/cache_full_20261015_v3/decoded')

AD_SDK_MARKERS = ('/mbridge', '/.mbridge700', '/MBridge', '/UnityAdsCache', '/mb/res/', '/mb/other/', '/mb/config/')
JUNK_NAMES = {'.DS_Store', '.nomedia'}


def load_shard_records():
    records = {}
    truncated = 0
    for shard in sorted(SHARDS.glob('chunk_*.jsonl')):
        for line in shard.open(encoding='utf-8'):
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                truncated += 1
                continue
            records[rec['path']] = rec  # 同路径后写覆盖（重跑修正）
    return records, truncated


def classify_other(row):
    """Non-bdl, non-data5 rows -> ledger status with reason."""
    path = row['path']
    name = path.rsplit('/', 1)[-1]
    if path.startswith('cache/UnityShaderCache/'):
        return 'excluded_engine_cache', 'Unity runtime compiled-shader binary cache; regenerated by engine, not game assets'
    if name in JUNK_NAMES or '/__MACOSX/' in path or name.startswith('._'):
        return 'excluded_junk', 'macOS metadata / placeholder file, no game content'
    if any(m in path for m in AD_SDK_MARKERS):
        return 'excluded_ad_sdk', 'Mintegral/UnityAds advertising SDK cache, not game resources'
    if path.startswith('files/il2cpp/'):
        return 'engine_file_reused', ('IL2CPP runtime file; global-metadata.dat already decoded in earlier phase '
                                      '(work/protection/metadata_aei_decoded.bin); dll-resources are .NET resources')
    return 'unclassified', 'no rule matched; needs review'


def main():
    global OUTPUT, SHARDS, V3_DECODED
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--inventory', type=Path, default=INVENTORY)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--shards', type=Path, default=SHARDS)
    parser.add_argument('--v3-decoded', type=Path, default=V3_DECODED)
    args = parser.parse_args()

    OUTPUT, SHARDS, V3_DECODED = args.output, args.shards, args.v3_decoded
    rows = [json.loads(line) for line in args.inventory.open(encoding='utf-8')]
    shard_records, truncated = load_shard_records()
    print(f'shard records: {len(shard_records)}, truncated lines skipped: {truncated}')

    ledger = []
    stats = Counter()
    obj_types = Counter()
    objects_exported = 0
    for row in rows:
        path = row['path']
        entry = {
            'path': path,
            'source_snapshot': row['archive'].split('/')[1] if '/' in row['archive'] else row['archive'],
            'archive': row['archive'],
            'archive_member': row['archive_member'],
            'local_path': row['work_file'],
            'size': row['bytes'],
            'phone_mtime': row['phone_mtime'],
            'basis': row['basis'],
        }
        if path.endswith('.data5'):
            name = path.rsplit('/', 1)[-1]
            decoded = V3_DECODED / (name + '.json.raw')  # v3 完整解码 JSON 字节
            entry.update(
                detected_format='data5_native_aes_gzip_json',
                processing_status='already_decoded_prior',
                output_path=str(decoded) if decoded.exists() else None,
                error_or_unknown_reason=None if decoded.exists() else 'decoded json.raw missing in v3',
            )
            stats['data5_' + ('ok' if decoded.exists() else 'missing')] += 1
        elif path.endswith('.bdl'):
            rec = shard_records.get(path)
            if rec is None:
                entry.update(detected_format='bdl_xor_unityfs', processing_status='not_processed',
                             output_path=None, error_or_unknown_reason='no shard record (run not finished)')
                stats['bdl_not_processed'] += 1
            else:
                entry.update(detected_format='bdl_xor_unityfs',
                             processing_status=rec['status'],
                             output_path=rec.get('output_path'),
                             error_or_unknown_reason=rec.get('error_or_unknown_reason'))
                for k in ('source_sha256', 'decoded_sha256', 'decoded_bytes', 'tail_unchanged',
                          'object_types', 'objects_exported'):
                    if k in rec:
                        entry[k] = rec[k]
                stats['bdl_' + rec['status']] += 1
                for t, n in rec.get('object_types', {}).items():
                    obj_types[t] += n
                objects_exported += rec.get('objects_exported', 0)
        else:
            status, reason = classify_other(row)
            entry.update(detected_format=status, processing_status=status,
                         output_path=None, error_or_unknown_reason=reason)
            stats[status] += 1
        ledger.append(entry)

    OUTPUT.mkdir(parents=True, exist_ok=True)
    with (OUTPUT / 'ledger.jsonl').open('w', encoding='utf-8') as fh:
        for entry in ledger:
            fh.write(json.dumps(entry, ensure_ascii=False) + '\n')

    coverage = {
        'input_total': len(rows),
        'by_processing_status': dict(stats.most_common()),
        'bdl_object_types': dict(obj_types.most_common()),
        'bdl_objects_exported': objects_exported,
        'shard_truncated_lines': truncated,
        'notes': [
            'bdl status ok = all objects exported; partial = some object export failed (raw bytes saved when possible); error = container decode/load failed.',
            'objects_exported counts objects, not input files; AssetBundle manifests included.',
            'already_decoded_prior: 77 data5 decoded and verified in cache_full_20261015_v3 (unchanged in refresh).',
        ],
    }
    (OUTPUT / 'coverage.json').write_text(json.dumps(coverage, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

    # 附加索引：从包名提取角色ID（cha_2d_*_<cid>、char<cid>_*、VOICE_<cid>_* 等命名规律）
    cid_index = defaultdict(list)
    pat = re.compile(r'(?:cha_2d_\w+?|char|VOICE|voice)_0*(\d{4,6})(?:\.bdl|_|$)')
    for entry in ledger:
        if not entry['path'].endswith('.bdl') or entry['processing_status'] not in ('ok', 'partial'):
            continue
        name = entry['path'].rsplit('/', 1)[-1]
        m = pat.search(name)
        if m:
            cid_index[int(m.group(1))].append(entry['output_path'])
    cid_doc = {
        'note': 'Name-based auxiliary index only; NOT proof of in-game binding. Patterns: cha_2d_*_<cid>, char<cid>_*, VOICE_<cid>_*. Coverage limited to files following these naming rules.',
        'cid_count': len(cid_index),
        'index': {str(cid): sorted(paths) for cid, paths in sorted(cid_index.items())},
    }
    (OUTPUT / 'cid_index.json').write_text(json.dumps(cid_doc, ensure_ascii=False) + '\n', encoding='utf-8')
    print(json.dumps(coverage['by_processing_status'], ensure_ascii=False, indent=2))
    print('objects exported:', objects_exported, '| cid index:', len(cid_index))


if __name__ == '__main__':
    main()
